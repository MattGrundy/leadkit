package team

// Starter-SOP generation (queue-mode-enforcement item 6 / GAP-5): a tame project with
// no hand-written SOP (cfg.SopFile empty, or pointing at a file that doesn't exist)
// gets nothing telling its team how to run — Capture fills that gap with a short,
// project-agnostic starter instead of silently producing an empty team_dir.

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

// starterSOPMarker is the FIRST line of every leadkit-generated starter SOP — the
// visible, greppable distinction between "leadkit wrote this" and "a human wrote
// this" that captureSop's non-clobber check (and `team status`'s drift check) rely
// on, alongside captured.yaml's own Sop.Generated field.
const starterSOPMarker = "<!-- leadkit: GENERATED STARTER SOP — replace with your project's own -->"

// starterSOP is the built-in template: the minimum operating loop, kept short and
// project-agnostic (NOT a copy of any one project's real SOP) — a real starting
// point a team edits from, not a finished document.
func starterSOP() string {
	return starterSOPMarker + `

# Autonomous Team SOP (generated starter)

This file was generated by ` + "`leadkit team capture`" + ` / ` + "`leadkit team scaffold`" + ` because this
project has no SOP of its own yet. Replace it with your project's own operating
model — this is a floor, not a finished document.

## The minimum operating loop

1. **Queue mode is the substrate.** Work is coordinated through the disk queue
   (` + "`leadkit queue`" + `/` + "`leadkit review send`" + `/` + "`leadkit gate verdict`" + `), never message-driven
   SendMessage-only coordination — the waker daemon, PM-board sync, audit, and
   merge-guard only see work that goes through the queue.
2. **Owner implements**, verifies the full test suite green, then
   ` + "`git commit --no-verify`" + ` (source-only — never bundle a verdict artifact into a
   commit).
3. **Enqueue a gate task** for the standing reviewer pool (` + "`leadkit review send`" + `)
   rather than asking a reviewer directly — that's what puts the ticket where the
   pool's own queue-pull loop finds it.
4. **The gate is chained:** code-review (correctness/reuse) must be ready before
   critique (consistency/conflicts) can record; each layer comes
   from a DIFFERENT kind of reviewer — see ` + "`internal/gate`" + `'s layer-independence rule.
   Record every verdict through ` + "`leadkit gate verdict`" + ` (it records AND reconciles
   the ticket's queue location/frontmatter as one action), never by hand.
5. **The lead pushes only once a ticket is fully GATED.** Nothing else pushes.
6. **Rest between polls.** An idle agent waits on its queue lane (fsnotify), it
   does not busy-poll.

## Replace this file

Once your project has its own SOP, point ` + "`team.sop_file`" + ` at it and re-run
` + "`leadkit team capture`" + ` — a real SOP is NEVER overwritten by a re-generated
starter (see captureSop's non-clobber rule).
`
}

// isGeneratedStarter reports whether data is (still) a leadkit-generated starter —
// i.e. its first non-blank content is starterSOPMarker — so captureSop can tell a
// prior starter (safe to regenerate) from a hand-written SOP (never overwrite) sitting
// at the same destination.
func isGeneratedStarter(data []byte) bool {
	return bytes.HasPrefix(bytes.TrimLeft(data, " \t\r\n"), []byte(starterSOPMarker))
}

// captureSop resolves what Capture should write to <TeamDir>/AUTONOMOUS-TEAM-SOP.md
// and does it: cfg.SopFile's real content when it exists and is readable; otherwise a
// generated starter — UNLESS the destination already holds a real (non-generated)
// SOP, which is NEVER overwritten. written reports whether a write happened this run
// (false when an existing hand-written SOP was correctly left untouched).
func captureSop(cfg Config) (file *CapturedFile, generated, written bool, err error) {
	dest := filepath.Join(cfg.TeamDir, "AUTONOMOUS-TEAM-SOP.md")

	if cfg.SopFile != "" {
		data, rerr := os.ReadFile(cfg.SopFile)
		if rerr == nil {
			if werr := os.WriteFile(dest, data, 0o644); werr != nil {
				return nil, false, false, fmt.Errorf("team: write AUTONOMOUS-TEAM-SOP.md: %w", werr)
			}
			return &CapturedFile{Name: "AUTONOMOUS-TEAM-SOP.md", Size: int64(len(data))}, false, true, nil
		}
		if !os.IsNotExist(rerr) {
			return nil, false, false, fmt.Errorf("team: read sop_file %s: %w", cfg.SopFile, rerr)
		}
		// sop_file is configured but the file doesn't exist — fall through to the
		// starter, same as sop_file being unset entirely.
	}

	if existing, rerr := os.ReadFile(dest); rerr == nil && !isGeneratedStarter(existing) {
		// A real, hand-written SOP already sits in team_dir (captured earlier from a
		// sop_file that has since gone missing, or authored directly there) — NEVER
		// clobber it with a generic starter.
		return &CapturedFile{Name: "AUTONOMOUS-TEAM-SOP.md", Size: int64(len(existing))}, false, false, nil
	}

	content := []byte(starterSOP())
	if err := os.WriteFile(dest, content, 0o644); err != nil {
		return nil, false, false, fmt.Errorf("team: write starter AUTONOMOUS-TEAM-SOP.md: %w", err)
	}
	return &CapturedFile{Name: "AUTONOMOUS-TEAM-SOP.md", Size: int64(len(content))}, true, true, nil
}
