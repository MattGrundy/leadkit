package commentscan

import (
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"testing"
)

func write(t *testing.T, root, rel, body string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestFiles_GitCheckoutExcludesIgnoredState(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not installed")
	}
	dir := t.TempDir()
	if out, err := exec.Command("git", "-C", dir, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	write(t, dir, ".gitignore", "/scratch/\n")
	write(t, dir, "a.go", "package a\n")
	write(t, dir, "internal/queue/q.go", "package q\n")
	write(t, dir, "scratch/leak.go", "package s\n")
	write(t, dir, "tasks/t.go", "package t\n")
	got, err := Files(dir, ".go")
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"a.go", "internal/queue/q.go"}; !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

func TestFiles_WalkSkipsLocalState(t *testing.T) {
	dir := t.TempDir()
	for _, p := range []string{"a.go", ".claude/worktrees/w/x.go", "team/x.go", "queue/x.go", "internal/queue/q.go", "internal/vendor/v.go"} {
		write(t, dir, p, "package a\n")
	}
	got, err := Files(dir, ".go")
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"a.go", "internal/queue/q.go"}; !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

func TestIsGenerated(t *testing.T) {
	for src, want := range map[string]bool{
		"// Code generated by gen. DO NOT EDIT.\n\npackage a\n":                 true,
		"package a\n\n// Code generated by gen. DO NOT EDIT.\n":                 true,
		"package a\n\n// mentions Code generated ... DO NOT EDIT. in passing\n": false,
		"package a\n\nvar s = \"// Code generated x DO NOT EDIT.\"\n":           false,
		"// Code generated by gen.\n// DO NOT EDIT.\n":                          false,
	} {
		if got := IsGenerated([]byte(src)); got != want {
			t.Errorf("%q: got %v, want %v", src, got, want)
		}
	}
}

func TestIsHistory(t *testing.T) {
	for text, want := range map[string]bool{
		"This used to run twice.":       true,
		"It is used to detect skew.":    false,
		"The caller can no longer see.": true,
		"returns the id.":               false,
	} {
		if got := IsHistory(text); got != want {
			t.Errorf("%q: got %v, want %v", text, got, want)
		}
	}
}
